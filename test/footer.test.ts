import { describe, it, expect } from 'vitest';
import { createPreviewer } from '../src/controller';
import type { LayoutSnapshot, PreviewPage } from '../src/types';

function pageSvg(n: number, w = 200, h = 300): string {
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}" viewBox="0 0 ${w} ${h}"><text>page ${n}</text></svg>`;
}

function pages(count: number): PreviewPage[] {
  return Array.from({ length: count }, (_, i) => ({ svg: pageSvg(i + 1), width: 200, height: 300 }));
}

function snapshotWithMeta(meta: LayoutSnapshot['meta']): LayoutSnapshot {
  return {
    version: 1,
    pages: [{ width: 200, height: 300 }],
    root: { id: 'n0', type: 'Document', rects: [], children: [] },
    meta,
  };
}

describe('footer', () => {
  it('renders no footer by default', () => {
    const div = document.createElement('div');
    document.body.append(div);
    createPreviewer(div, {});
    expect(div.querySelector('.bpp-footer')).toBeNull();
    div.remove();
  });

  it('renders the default text and conformance pills from the loaded snapshot', () => {
    const div = document.createElement('div');
    document.body.append(div);
    const handle = createPreviewer(div, { footer: {} });
    handle.load(pages(1), { snapshot: snapshotWithMeta({ accessibilityMode: 1, conformance: 'PdfA2a' }) });

    const footer = div.querySelector<HTMLElement>('.bpp-footer');
    expect(footer).not.toBeNull();
    expect(div.querySelector('.bpp-footer-text')?.textContent).toBe('Generated by @bonniepdf/previewer');
    const pills = [...div.querySelectorAll('.bpp-footer-tag')].map(el => el.textContent);
    expect(pills).toEqual(['PDF/A-2a', 'PDF/UA-1']);
    div.remove();
  });

  it('honours a custom text and disables pills with conformance: false', () => {
    const div = document.createElement('div');
    document.body.append(div);
    const handle = createPreviewer(div, { footer: { text: 'Acme docs', conformance: false } });
    handle.load(pages(1), { snapshot: snapshotWithMeta({ accessibilityMode: 1, conformance: 'PdfA2b' }) });

    expect(div.querySelector('.bpp-footer-text')?.textContent).toBe('Acme docs');
    expect(div.querySelectorAll('.bpp-footer-tag')).toHaveLength(0);
    div.remove();
  });

  it('shows no pills for a document without PDF/A conformance or tagging', () => {
    const div = document.createElement('div');
    document.body.append(div);
    const handle = createPreviewer(div, { footer: {} });
    handle.load(pages(1), { snapshot: snapshotWithMeta({ accessibilityMode: 0, conformance: 'None' }) });
    expect(div.querySelectorAll('.bpp-footer-tag')).toHaveLength(0);

    // A load without any snapshot leaves the previous pills cleared.
    handle.load(pages(1));
    expect(div.querySelectorAll('.bpp-footer-tag')).toHaveLength(0);
    div.remove();
  });
});
